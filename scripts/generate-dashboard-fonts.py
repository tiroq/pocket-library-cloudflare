#!/usr/bin/env python3
"""Generate compact, deterministic monochrome glyph atlases from OFL font sources.

Maintainer-only operation. Fonts are fetched temporarily into memory; no
TTF/OTF/WOFF files are committed or shipped to the Worker or user.
Requires Python 3.10+ and Pillow 11+.
"""
from __future__ import annotations

import base64
import io
import json
import pathlib
import urllib.request
from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "generated" / "dashboard-font-atlases.js"
FONTS = {
    "golos-text": {
        "url": "https://raw.githubusercontent.com/google/fonts/main/ofl/golostext/GolosText%5Bwght%5D.ttf",
        "variable": True,
    },
    "inter": {
        "url": "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz%2Cwght%5D.ttf",
        "variable": True,
    },
    "ibm-plex-sans": {
        "url": "https://raw.githubusercontent.com/IBM/plex/master/packages/plex-sans/fonts/complete/ttf/IBMPlexSans-{weight}.ttf",
        "variable": False,
    },
    "onest": {
        "url": "https://raw.githubusercontent.com/google/fonts/main/ofl/onest/Onest%5Bwght%5D.ttf",
        "variable": True,
    },
}
# Pixel sizes and actual font weights. These match the X3 dashboard spec.
ROLES = {
    "date": (34, 600),
    "heading": (17, 500),
    "time": (21, 600),
    "body": (22, 400),
    "footer": (12, 400),
}
# Latin/extended Latin, Cyrillic including Yo/yo and common punctuation.
CODEPOINTS = [
    *range(0x20, 0x180),
    *range(0x400, 0x530),
    *range(0x2000, 0x2070),
    0x20BD, 0x20AC, 0x2116, 0x2122, 0x2190, 0x2192, 0x2212, 0x25A1,
]


def get_font(name: str, source: bytes, size: int, weight: int):
    if name == "ibm-plex-sans":
        return ImageFont.truetype(io.BytesIO(source), size=size)
    font = ImageFont.truetype(io.BytesIO(source), size=size)
    axes = font.get_variation_axes()
    settings = []
    found = False
    for axis in axes:
        label = axis["name"].decode("ascii", "ignore").lower()
        value = axis["default"]
        if "weight" in label:
            value = weight
            found = True
        elif "optical" in label:
            value = size
        settings.append(min(axis["maximum"], max(axis["minimum"], value)))
    if not found:
        raise RuntimeError(f"{name} did not expose a weight variation axis")
    font.set_variation_by_axes(settings)
    return font


def glyph_record(font, ch: str):
    mask, (dx, dy) = font.getmask2(ch, mode="L", anchor="ls")
    width, height = mask.size
    advance = round(font.getlength(ch) * 64) / 64
    raw = bytes(mask)
    # Crop away untouched transparent borders, preserving baseline offsets.
    xs, ys = [], []
    for y in range(height):
        for x in range(width):
            if raw[y * width + x] >= 128:
                xs.append(x)
                ys.append(y)
    if not xs:
        return [advance, 0, 0, 0, 0, ""]
    x0, y0, x1, y1 = min(xs), min(ys), max(xs) + 1, max(ys) + 1
    w, h = x1 - x0, y1 - y0
    rowbytes = (w + 7) // 8
    packed = bytearray(rowbytes * h)
    for y in range(h):
        for x in range(w):
            if raw[(y0 + y) * width + (x0 + x)] >= 128:
                packed[y * rowbytes + (x // 8)] |= 128 >> (x % 8)
    return [advance, dx + x0, dy + y0, w, h, base64.b64encode(packed).decode("ascii")]


def download(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "PocketLibrary-FontAtlas/1.0"}), timeout=45) as response:
        return response.read()


def main():
    atlases = {}
    for name, spec in FONTS.items():
        print("Rendering", name, flush=True)
        primary = download(spec["url"].replace("{weight}", "Regular"))
        styles = {}
        fonts_by_weight = {400: primary}
        if not spec["variable"]:
            fonts_by_weight[500] = download(spec["url"].replace("{weight}", "Medium"))
            fonts_by_weight[600] = download(spec["url"].replace("{weight}", "SemiBold"))
        for role, (size, weight) in ROLES.items():
            font = get_font(name, fonts_by_weight[weight], size, weight)
            ascent, descent = font.getmetrics()
            glyphs = {}
            for cp in CODEPOINTS:
                ch = chr(cp)
                if ch in glyphs:
                    continue
                # Skip chars the font cannot encode: draw fallback '?' at runtime.
                glyphs[ch] = glyph_record(font, ch)
            styles[role] = {"ascent": ascent, "descent": descent, "glyphs": glyphs}
            print(f"  {role:8s} {size}px/{weight} glyphs={len(glyphs)}", flush=True)
        atlases[name] = styles
    OUT.parent.mkdir(parents=True, exist_ok=True)
    content = ("// AUTO-GENERATED by scripts/generate-dashboard-fonts.py; DO NOT EDIT.\n"
               "// Rasterized glyphs derived from SIL OFL 1.1 fonts. See docs/dashboard-fonts.md.\n"
               "export const FONT_ATLASES = " + json.dumps(atlases, ensure_ascii=False, separators=(",", ":")) + ";\n")
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT}: {len(content.encode('utf-8')):,} bytes", flush=True)


if __name__ == "__main__":
    main()
